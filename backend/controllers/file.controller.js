import mongoose from 'mongoose'
import fs from 'node:fs/promises'
import sysPath from 'node:path'

import File from '@models/file.model.js'

import { isNull } from '@util/util.js'
import HttpStatusCodes from '@util/httpStatus.js'

const {
	OK,
	CREATED,
	BAD_REQUEST,
	NOT_FOUND,
	INTERNAL_SERVER_ERROR
} = HttpStatusCodes;


/**
 * 
 * @param {*} req 
 * @param {*} res 
 * @returns 
 */
const getFileRefs = async (req, res) => {
	try {
		// Attempt async call to get all Files
		const files = await File.find();
		// Access files via res.data in axios request on frontend
		return res.status(OK).send(files); 
	} catch (err) {
		return res.status(NOT_FOUND).send({ 
			success: false,
			message: 'Could not locate Files',
			error: err
		});
	}
};

/**
 * 
 * @param {*} req 
 * @param {*} res 
 * @returns 
 */
const createFileRefs = async (req, res) => {
	// In-memory array for response data
	const newFiles = [];
	// Read files from request data (after processing by multer middleware)
	const files = req.files;
	
	/**
	 * Callback func: create a mongoose File object for each uploaded file
	 */
	const createFilePromises = files.map(async (file) => {
  	// Destructure multer file object, create db model object
		const { filename, originalname, path } = file;
		const newFile = new File({ 
			name: originalname, // The file's original name
			path: sysPath.resolve(path),
			uniquename: filename // Unique name generated by multer
		});
		try {
			await newFile.save();
			newFiles.push(newFile);
			return newFile;
		} catch (err) {
			console.log(err);
			throw err;
		}
	});

	// Attempt async create Files
	try {
		const newFiles = await Promise.all(createFilePromises);
		return res.status(CREATED).send({ 
			success: true,
			message: 'Created Files',
			data: newFiles // TODO: serialize more efficiently 
		});
	} catch (err) {
		return res.status(INTERNAL_SERVER_ERROR).send({
			success: false,
			message: 'Could not create Files',
			error: err
		});
	}
};

/**
 * 
 * @param {*} req 
 * @param {*} res 
 * @returns 
 */
const deleteFileRef = async (req, res) => {
	// Get File object id from request header params
	const { id } = req.params;
	// Ensure id is valid (shortcut 404 check)
	if (!mongoose.Types.ObjectId.isValid(id)) {
		return res.status(BAD_REQUEST).send({
			success: false,
			message: `Invalid object id ${id}`
		});
	}
	// Attempt async delete the File
	try {
		const deletedFile = await File.findByIdAndDelete(id);
		// Check for non-existent File
		if (isNull(deletedFile)) {
			return res.status(NOT_FOUND).send({
				success: false,
				message: `File ${id} not found`
			});
		}
		// Attempt async delete file from file system
		await fs.unlink(deletedFile.path);
		return res.status(OK).send({
			success: true,
			message: `Deleted File ${id}`,
			data: deletedFile
		});
	} catch (err) {
		// Handle errors generated by file system
		if (err.code === 'ENOENT') {
			return res.status(NOT_FOUND).send({
				success: false,
				message: `File ${id} not found`,
				error: err
			});
		}
		// Handle general server errors
		return res.status(INTERNAL_SERVER_ERROR).send({
			success: false,
			message: `Could not delete File ${id}`,
			error: err
		});
	}
};

export { createFileRefs, deleteFileRef, getFileRefs }