export const uploadFiles = async (req, res) => {
	const files = req.files;
	const newFiles = []; // In-memory array to store data for response

	const createFilePromises = files.map(async (file) => {
  	const { filename, originalname, path } = file;
  	const newFile = new File({ filename, originalname, path });
		try {
			await newFile.save();
			newFiles.push(newFile);
			return newFile;
		} catch (err) {
			throw err;
		}
	});

	try {
		const newFiles = await Promise.all(createFilePromises);
		return res.status(201).send({ success: true, message: 'Created files', data: newFiles });
	} catch (err) {
		return res.status(500).send({ success: false, message: 'Error processing files', error: err });
	}
};


export const deleteUploadedFile = async (req, res) => {
	// Get the file id from request header params
	const { id } = req.params;

	// Ensure id is valid (shortcut 404 check)
	if (!mongoose.Types.ObjectId.isValid(id)) {
		return res.status(404).json({ success: false, message: 'Invalid file id', data: id });
	}

	try {
		// async delete the file's database reference
		const deletedFile = await File.findByIdAndDelete(id);
		// If no entry for 'id', deletedFile will be null
		if (deletedFile === null || deletedFile === undefined) {
			return res.status(404).send({ success: false, message: 'File not found on database', data: id });
		}
		// async delete the file from the file system
		await fs.unlink(deletedFile.path);
		return res.status(200).send({ success: true, message: 'Deleted file', data: deletedFile });
	} catch (err) {
		// Catch errors generated by file system
		if (err.code === 'ENOENT') {
			return res.status(404).send({ success: false, message: `File id=${id} not found on disk`, data: err })
		}
		// General errors
		return res.status(500).send({ success: false, message: `Could not delete file id=${id}`, data: err });
	}
};