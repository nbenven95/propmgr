import mongoose from 'mongoose'
import fs from 'node:fs/promises'

import File from '@models/file.model.js'

export const getUploadedFiles = async (req, res) => {
	try {
		const files = await File.find();
		return res.status(200).send(files); // Just send 'files' so we can access via res.data instead of res.data.data
	} catch (err) {
		return res.status(404).send({ success: false, message: 'Could not find files', data: err });
	}
};

