/**
 * 
 * @param {*} req 
 * @param {*} res 
 * @returns 
 */
const uploadFiles = async (req, res) => {
	// In-memory array for response data
	const newFiles = [];
	// Read files from request data (after processing by multer middleware)
	const files = req.files;
	/* Helper callback to create a FileRef promise for each uploaded file */
	const createFileRefPromises = files.map(async (file) => {
  	// Create new FileRef from form data (after processing by multer)
		const { filename, originalname, path } = file;
		const newFileRef = new FileRef({ 
			name: originalname, // The file's original name
			path: sysPath.resolve(path),
			uniquename: filename // Unique name generated by multer
		});
		try {
			// Await save FileRef to database
			await newFileRef.save();
			// Add to 
			newFiles.push(newFileRef);
			return newFileRef;
		} catch (err) {
			// Handle server side error for individual FileRef creation
			return res.status(INTERNAL_SERVER_ERROR).send({
				success: false,
				message: 'Could not create FileRef',
				error: err
			});
		}
	});
	try {
		// Await create FileRef promises for uploaded files
		const newFileRefs = await Promise.all(createFileRefPromises);
		return res.status(CREATED).send({ 
			success: true,
			message: 'Created FileRefs',
			data: newFileRefs // Return list of FileRefs so we can display file metadata on frontend
		});
	} catch (err) {
		// Handle general server side errors
		return res.status(INTERNAL_SERVER_ERROR).send({
			success: false,
			message: 'Could not create FileRefs',
			error: err
		});
	}
};

