import mongoose from 'mongoose'
import fs from 'node:fs/promises'
import sysPath from 'node:path'

import HttpStatusCodes from '@util/HttpStatus.js'

import FileRef from '@models/fileRef.model.js'

const {
	BAD_REQUEST,
	CREATED,
	CONFLICT,
	INTERNAL_SERVER_ERROR,
	NOT_FOUND,
	OK
} = HttpStatusCodes;

/**
 * Get all FileRefs
 * 
 * @param {*} req 
 * @param {*} res 
 * @returns 
 */
const getFileRefs = async (req, res) => {
	try {
		// Await get all FileRefs
		const fileRefs = await FileRef.find().populate('documents').exec();
		// Request failed, no FileRefs
		if (!fileRefs) {
			return res.status(NOT_FOUND).send({
				success: false,
				message: 'No FileRefs'
			});
		}
		// Request success: access data directly from axios response via res.data (frontend)
		return res.status(OK).send(fileRefs);
	} catch (err) {
		// Handle general server side errors
		return res.status(INTERNAL_SERVER_ERROR).send({ 
			success: false,
			message: 'Could not get FileRefs',
			error: err
		});
	}
};

