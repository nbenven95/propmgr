/**
 * 
 * @param {*} req 
 * @param {*} res 
 * @returns 
 */
const deleteFileRefAndFile = async (req, res) => {
	const { id } = req.params;
	// Ensure id is valid
	if (!mongoose.Types.ObjectId.isValid(id)) {
		return res.status(BAD_REQUEST).send({
			success: false,
			message: `Invalid object id: ${id}`
		});
	}
	// Await delete FileRef
	try {
		// First, ensure the file is not linked to any documents
		const fileToBeDeleted = await FileRef.findById(id).populate('documents').exec();
		if (fileToBeDeleted.documents?.length !== 0) {
			return res.status(CONFLICT).send({
				success: false,
				message: `Could not delete FileRef with id ${id}: FileRef is linked to other resources`
			});
		}
		const deletedFile = await FileRef.findByIdAndDelete(id);
		// Request failed, no FileRef for id
		if (!deletedFile) {
			return res.status(NOT_FOUND).send({
				success: false,
				message: `Could not find FileRef with id ${id}`
			});
		}
		// Await delete file from local disk
		await fs.unlink(deletedFile.path);
		return res.status(OK).send({
			success: true,
			message: `Deleted FileRef with id ${id}`,
			data: deletedFile
		});
	} catch (err) {
		// Handle errors generated by file system
		if (err.code === 'ENOENT') {
			return res.status(NOT_FOUND).send({
				success: false,
				message: `Could not find FileRef with id ${id}`,
				error: err
			});
		}
		// Handle general server errors
		return res.status(INTERNAL_SERVER_ERROR).send({
			success: false,
			message: `Could not delete FileRef with id ${id}`,
			error: err
		});
	}
};

export { uploadFiles, downloadFile, getFileRefById, getFileRefs, deleteFileRefAndFile };